def add_otc_docs_to_chromadb():
    """OTC 약품 문서를 ChromaDB에 추가"""
    import sys, os
    sys.path.insert(0, os.path.join(os.path.dirname(__file__), '..'))
    from eval.setup import collection, embed_model

    existing = collection.get(include=['documents'])
    existing_docs = set(existing['documents'])
    current_count = len(existing_docs)

    added = 0
    for i, doc in enumerate(OTC_DOCUMENTS):
        if doc in existing_docs:
            print(f'  [skip] 이미 존재: {doc[:30]}...')
            continue
        doc_id = f'otc_{i:03d}'
        emb = embed_model.encode([doc]).tolist()
        collection.add(
            ids=[doc_id],
            documents=[doc],
            embeddings=emb,
        )
        added += 1
        print(f'  [추가] {doc[:50]}...')

    print(f'\n완료: {added}개 추가 (기존 {current_count}개 → 현재 {collection.count()}개)')


if __name__ == '__main__':
    add_otc_docs_to_chromadb()
